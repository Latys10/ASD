# ============================================================
# Лабораторная №15. ОДНОСВЯЗНЫЙ СПИСОК (без функций def)
# Условие сортировки: УБЫВАНИЕ суммы цифр дробной части числа.
# Пример: 5.12  5.20  5.05  ->  5.05 (5)  5.12 (3)  5.20 (2)
# Узел списка = словарь {"data": число, "key": сумма цифр, "next": ссылка}
# ============================================================

head = None                      # ссылка на первый узел; None = список пуст
size = 0                         # количество элементов в списке
to_add = []                      # очередь добавления: пары (число, позиция)
                                 # позиция: 0 = в начало, -1 = в конец, k = по индексу k

print("Вводите числа по одному (пустая строка - конец ввода):")  # N заранее неизвестно
while True:                      # цикл ввода начальной последовательности
    s = input("> ").strip().replace(",", ".")   # читаем строку, запятую меняем на точку
    if s == "":                  # пустая строка означает конец последовательности
        break                    # выходим из цикла ввода
    try:                         # пробуем превратить строку в вещественное число
        to_add.append((float(s), -1))   # кладём число в очередь, добавим в конец
    except ValueError:           # если это не число
        print("Это не число, повторите")   # сообщаем об ошибке

while True:                      # главный цикл программы (меню)

    # ---------- ДОБАВЛЕНИЕ: обрабатываем всё, что лежит в очереди ----------
    for value, pos in to_add:    # берём из очереди число и позицию вставки
        s = str(abs(value))      # число без знака в виде строки, например "5.12"
        key = 0                  # сумма цифр дробной части, пока 0
        if "." in s:             # если в записи есть точка
            for ch in s.split(".")[1]:   # перебираем символы после точки
                if ch.isdigit():         # если символ - цифра
                    key += int(ch)       # прибавляем её к сумме
        node = {"data": value, "key": key, "next": None}   # создаём новый узел

        if head is None or pos == 0:     # список пуст ИЛИ вставка в начало
            node["next"] = head          # новый узел указывает на старую голову
            head = node                  # голова теперь новый узел
        elif pos == -1 or pos == size:   # вставка в конец
            cur = head                   # начинаем обход с головы
            while cur["next"] is not None:   # идём, пока не дойдём до последнего узла
                cur = cur["next"]        # переходим к следующему узлу
            cur["next"] = node           # последний узел теперь указывает на новый
        else:                            # вставка в середину по индексу pos
            prev = head                  # prev - узел, после которого вставим
            for _ in range(pos - 1):     # проходим pos-1 шагов от головы
                prev = prev["next"]      # сдвигаемся на следующий узел
            node["next"] = prev["next"]  # новый узел указывает на то, что шло после prev
            prev["next"] = node          # prev теперь указывает на новый узел
        size += 1                        # размер списка вырос на 1
    to_add = []                  # очередь обработана, очищаем её

    # ---------- ВЫВОД СПИСКА ----------
    items = []                   # сюда соберём строки со значениями
    cur = head                   # начинаем обход с головы
    while cur is not None:       # пока не дошли до конца списка
        items.append(str(cur["data"]))   # добавляем значение узла как строку
        cur = cur["next"]        # переходим к следующему узлу
    print("\nСписок:", " -> ".join(items) + " -> None" if items else "пуст")  # печатаем
    print("Размер:", size)       # печатаем размер

    # ---------- МЕНЮ ----------
    print("1-добавить в начало  2-добавить в конец  3-вставить по индексу")
    print("4-удалить по значению  5-удалить по индексу  6-сортировать  0-выход")
    choice = input("Выбор: ").strip()    # читаем команду пользователя

    if choice == "0":            # выход
        break                    # завершаем главный цикл

    elif choice in ("1", "2", "3"):      # любое из добавлений
        try:                             # защита от неверного ввода
            v = float(input("Число: ").replace(",", "."))   # читаем число
            if choice == "1":            # в начало
                to_add.append((v, 0))    # кладём в очередь с позицией 0
            elif choice == "2":          # в конец
                to_add.append((v, -1))   # позиция -1 = конец
            else:                        # по индексу
                i = int(input("Индекс (0.." + str(size) + "): "))   # читаем индекс
                if 0 <= i <= size:       # проверяем допустимость
                    to_add.append((v, i))    # кладём в очередь
                else:
                    print("Неверный индекс")  # индекс вне диапазона
        except ValueError:               # ввели не число
            print("Ошибка ввода")

    elif choice == "4":          # удаление по значению
        try:
            v = float(input("Какое число удалить: ").replace(",", "."))   # читаем значение
            prev = None          # предыдущий узел (у головы его нет)
            cur = head           # текущий узел
            found = False        # флаг: нашли ли
            while cur is not None:           # обходим список
                if cur["data"] == v:         # нашли первое совпадение
                    if prev is None:         # удаляем голову
                        head = cur["next"]   # голова сдвигается на второй узел
                    else:                    # удаляем не голову
                        prev["next"] = cur["next"]   # предыдущий «перепрыгивает» cur
                    size -= 1                # размер уменьшился
                    found = True             # отмечаем успех
                    break                    # удаляем только первое вхождение
                prev = cur                   # запоминаем текущий как предыдущий
                cur = cur["next"]            # идём дальше
            print("Удалено" if found else "Не найдено")   # сообщение
        except ValueError:
            print("Ошибка ввода")

    elif choice == "5":          # удаление по индексу
        try:
            i = int(input("Индекс (0.." + str(size - 1) + "): "))   # читаем индекс
            if 0 <= i < size:    # проверка диапазона
                if i == 0:               # удаление головы
                    head = head["next"]  # голова = второй узел
                else:                    # удаление из середины/конца
                    prev = head          # ищем узел перед удаляемым
                    for _ in range(i - 1):   # i-1 шагов от головы
                        prev = prev["next"]  # сдвигаемся вперёд
                    prev["next"] = prev["next"]["next"]   # пропускаем удаляемый узел
                size -= 1                # размер уменьшился
                print("Удалено")
            else:
                print("Неверный индекс")
        except ValueError:
            print("Ошибка ввода")

    elif choice == "6":          # сортировка по убыванию суммы цифр дробной части
        if size >= 2:            # при 0 или 1 элементе сортировать нечего
            swapped = True       # флаг: были ли обмены за проход
            while swapped:       # повторяем проходы, пока есть обмены (пузырёк)
                swapped = False  # в начале прохода обменов нет
                cur = head       # начинаем с головы
                while cur["next"] is not None:   # сравниваем соседние узлы
                    nxt = cur["next"]            # следующий узел
                    if cur["key"] < nxt["key"]:  # у текущего сумма МЕНЬШЕ -> нужен обмен (убывание)
                        cur["data"], nxt["data"] = nxt["data"], cur["data"]   # меняем числа
                        cur["key"], nxt["key"] = nxt["key"], cur["key"]       # меняем ключи
                        swapped = True           # фиксируем обмен
                    cur = nxt                    # идём к следующей паре
        print("Отсортировано")

    else:                        # неизвестная команда
        print("Неизвестная команда")